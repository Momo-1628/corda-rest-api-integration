"""Records a real browser session driving Swagger UI against the live Seller (10050) and Buyer (10060) APIs."""
import json
import os
import shutil
import time

from playwright.sync_api import sync_playwright

OUT = r"D:\corda-rest-api-run\demo\browser\swagger"
shutil.rmtree(OUT, ignore_errors=True); os.makedirs(OUT)
SELLER, BUYER = "http://localhost:10050", "http://localhost:10060"
SKEY, BKEY = "seller-secret-key-123", "buyer-secret-key-456"
INV = "INV-SWAGGER-" + time.strftime("%H%M%S")

BANNER_JS = """(txt) => {
  let b = document.getElementById('demo-banner');
  if (!b) { b = document.createElement('div'); b.id = 'demo-banner'; document.body.appendChild(b); }
  b.textContent = txt;
  Object.assign(b.style, {position:'fixed', left:'0', right:'0', bottom:'0', zIndex: 2147483647,
    background:'rgba(11,26,51,0.95)', color:'#fff', font:'600 19px Segoe UI, sans-serif',
    padding:'12px 24px', borderTop:'4px solid #14C4B8'});
}"""


def banner(page, txt):
    page.evaluate(BANNER_JS, "Live demo  |  " + txt)


def op(page, method, path):
    return page.locator(f".opblock-{method}:has(.opblock-summary-path[data-path='{path}'])").first


def authorize(page, key):
    page.click("button.authorize"); time.sleep(0.8)
    page.locator(".modal-ux input[type=text]").first.type(key, delay=45); time.sleep(0.5)
    page.click(".modal-ux .auth-btn-wrapper button.authorize"); time.sleep(0.8)
    page.click(".modal-ux button.btn-done"); time.sleep(0.6)


def run(page, method, path, params=None, body=None, read=3.5):
    o = op(page, method, path)
    o.scroll_into_view_if_needed(); o.locator(".opblock-summary").click(); time.sleep(0.8)
    start_btn = o.locator("button.try-out__btn:not(.cancel):not(.reset)")
    if start_btn.count():
        start_btn.first.click(); time.sleep(0.6)
    clear = o.locator("button.btn-clear")
    if clear.count():
        clear.first.click(); time.sleep(0.4)
    for k, v in (params or {}).items():
        inp = o.locator(f"input[placeholder='{k}']").first
        inp.fill(""); inp.type(v, delay=12)
    if body is not None:
        ta = o.locator("textarea.body-param__text").first
        ta.fill(""); ta.type(body, delay=4); time.sleep(0.4)
    o.locator("button.execute").click()
    o.locator(".live-responses-table .response-col_status").first.wait_for(timeout=60000)
    time.sleep(0.8)
    resp = o.locator(".live-responses-table .response-col_description pre").first
    resp.scroll_into_view_if_needed()
    page.mouse.wheel(0, -120); time.sleep(read)
    text = resp.inner_text()
    status = o.locator(".live-responses-table .response-col_status").first.inner_text().strip()
    o.locator(".opblock-summary").first.click(); time.sleep(0.5)  # collapse again
    return status, text


with sync_playwright() as p:
    browser = p.chromium.launch(channel="chrome", headless=True)
    ctx = browser.new_context(viewport={"width": 1440, "height": 810}, record_video_dir=OUT,
                              record_video_size={"width": 1440, "height": 810})
    page = ctx.new_page()

    # ---- Seller API
    page.goto(SELLER + "/swagger-ui.html", wait_until="networkidle"); page.wait_for_selector(".opblock")
    banner(page, "Seller API (SellerCorp, port 10050) - OpenAPI / Swagger UI generated by springdoc")
    time.sleep(3); page.mouse.move(700, 450); page.mouse.wheel(0, 350); time.sleep(2.5); page.mouse.wheel(0, -350); time.sleep(1)

    banner(page, "Security - calling GET /api/invoices WITHOUT an API key -> 401 UNAUTHORIZED")
    st, _ = run(page, "get", "/api/invoices", read=3.5); print("no key:", st)

    banner(page, "Authorize - entering the seller's X-API-KEY")
    authorize(page, SKEY)

    banner(page, "Validation - POST /api/invoices with amount = -500 -> 400 VALIDATION_FAILED")
    bad = json.dumps({"invoiceNo": INV + "-BAD", "buyer": "O=BuyerCorp,L=Bengaluru,C=IN", "amount": -500,
                      "currency": "INR", "description": "invalid amount", "dueDate": "2026-12-31"}, indent=2)
    st, _ = run(page, "post", "/api/invoices", body=bad, read=3.5); print("bad:", st)

    banner(page, "POST /api/invoices -> IssueInvoiceFlow: seller + buyer sign, notary notarises -> 201 Created")
    body = json.dumps({"invoiceNo": INV, "buyer": "O=BuyerCorp,L=Bengaluru,C=IN", "amount": 87500.00,
                       "currency": "INR", "description": "Swagger demo - 25 server racks", "dueDate": "2026-12-31"}, indent=2)
    st, txt = run(page, "post", "/api/invoices", body=body, read=5); print("issue:", st)
    lid = json.loads(txt)["data"]["linearId"]

    # ---- Buyer API
    page.goto(BUYER + "/swagger-ui.html", wait_until="networkidle"); page.wait_for_selector(".opblock")
    banner(page, "Buyer API (BuyerCorp, port 10060) - the same invoice is already in the buyer's vault")
    time.sleep(2); authorize(page, BKEY)
    st, _ = run(page, "get", "/api/invoices/{linearId}", params={"linearId": lid}, read=4); print("buyer get:", st)

    banner(page, "PUT /api/invoices/{linearId}/pay on an ISSUED invoice -> 422 (contract rule: must be APPROVED first)")
    st, _ = run(page, "put", "/api/invoices/{linearId}/pay", params={"linearId": lid},
                body=json.dumps({"remarks": "trying to pay too early"}, indent=2), read=4.5); print("early pay:", st)

    banner(page, "PUT /api/invoices/{linearId}/approve -> ApproveInvoiceFlow (buyer signs) -> APPROVED")
    st, _ = run(page, "put", "/api/invoices/{linearId}/approve", params={"linearId": lid},
                body=json.dumps({"remarks": "Racks received and inspected"}, indent=2), read=4); print("approve:", st)

    banner(page, "PUT /api/invoices/{linearId}/pay -> PayInvoiceFlow -> PAID")
    st, _ = run(page, "put", "/api/invoices/{linearId}/pay", params={"linearId": lid},
                body=json.dumps({"remarks": "NEFT UTR HDFC0009876543"}, indent=2), read=4); print("pay:", st)

    banner(page, "Unknown linearId -> 404 INVOICE_NOT_FOUND")
    st, _ = run(page, "get", "/api/invoices/{linearId}", params={"linearId": "00000000-0000-0000-0000-000000000000"}, read=3)
    print("404:", st)

    # ---- back to the seller: audit trail
    page.goto(SELLER + "/swagger-ui.html", wait_until="networkidle"); page.wait_for_selector(".opblock")
    banner(page, "Seller API - GET /history: ISSUED -> APPROVED -> PAID (consumed + unconsumed states)")
    authorize(page, SKEY)
    st, _ = run(page, "get", "/api/invoices/{linearId}/history", params={"linearId": lid}, read=6); print("history:", st)
    banner(page, "Seller API - GET /api/invoices?status=PAID")
    st, _ = run(page, "get", "/api/invoices", params={"status": "PAID"}, read=5); print("paid list:", st)
    vid = page.video.path()
    ctx.close(); browser.close()
print("video:", vid, "linearId:", lid)
